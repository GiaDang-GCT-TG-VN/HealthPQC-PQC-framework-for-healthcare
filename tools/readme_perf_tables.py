"""
tools/readme_perf_tables.py — HealthPQC v2.0
Renders the README performance tables from the result CSVs, so every number in them is the
CSV's own value (no rounding):

  results/healthcare_benchmark.csv        -> Algorithm Performance (one row per use case)
  results/hybrid_keyx_benchmark.csv       -> Hybrid Key Exchange Performance (avg_ms)
  load_test/results/load_1000_stats.csv   -> the "P99 at 1000 Users" column (99% column)

The tables sit between the README markers PERF_START and PERF_END.

  python tools/readme_perf_tables.py           # print the tables
  python tools/readme_perf_tables.py --write   # update README.md
  python tools/readme_perf_tables.py --check   # exit 1 if README.md differs from the CSVs
"""

import csv
import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
README = os.path.join(REPO_ROOT, "README.md")
BENCH = os.path.join(REPO_ROOT, "results", "healthcare_benchmark.csv")
HYBRID = os.path.join(REPO_ROOT, "results", "hybrid_keyx_benchmark.csv")
LOAD = os.path.join(REPO_ROOT, "load_test", "results", "load_1000_stats.csv")
PERF_START = "<!-- perf-tables:start (generated by tools/readme_perf_tables.py; do not edit by hand) -->"
PERF_END = "<!-- perf-tables:end -->"

FIPS = {"203": "FIPS 203", "204": "FIPS 204", "205": "FIPS 205", "206": "draft FIPS 206 (FN-DSA)"}
# hybrid_keyx_benchmark.csv scenario -> load_1000_stats.csv Name
LOAD_NAME = {
    "Classical only (X25519)": "Classical (X25519)",
    "PQC only (ML-KEM-768)": "PQC Only (ML-KEM-768)",
    "Hybrid (X25519 + ML-KEM-768 + HKDF)": "Hybrid (X25519+ML-KEM-768)",
}


def _rows(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def _int(s):
    return f"{int(s):,}"


def algorithm_table():
    lines = ["### Algorithm Performance", "",
             "| Algorithm | NIST FIPS | KeyGen (ms) | Public Key (B) | Output (B) | Healthcare Use Case |",
             "|-----------|-----------|-------------|----------------|------------|---------------------|"]
    for r in _rows(BENCH):
        out = _int(r["output_bytes"])
        if r["algorithm"].startswith("Falcon"):
            out = f"about {out}"                        # Falcon signatures vary in length
        use = f"{r['use_case'].replace('_', ' ')} (NIST {r['security_level']})"
        lines.append(f"| **{r['algorithm']}** | {FIPS[r['fips']]} | {r['keygen_ms']} | "
                     f"{_int(r['public_key_bytes'])} | {out} | {use} |")
    return lines


def hybrid_table():
    p99 = {r["Name"]: r["99%"] for r in _rows(LOAD)}
    lines = ["### Hybrid Key Exchange Performance", "",
             "| Mode | Avg Latency (ms) | P99 at 1000 Users |",
             "|------|------------------|-------------------|"]
    for r in _rows(HYBRID):
        mode = r["scenario"]
        if mode.startswith("Hybrid"):
            mode = f"**{mode}**"
        lines.append(f"| {mode} | {r['avg_ms']} | {p99[LOAD_NAME[r['scenario']]]} ms |")
    return lines


def render():
    src = ("*Generated by `tools/readme_perf_tables.py` from `results/healthcare_benchmark.csv`, "
           "`results/hybrid_keyx_benchmark.csv` and `load_test/results/load_1000_stats.csv` (99% column).*")
    return "\n".join([PERF_START, ""] + algorithm_table() + [""] + hybrid_table() + ["", src, "", PERF_END])


def readme_section(text):
    a, b = text.index(PERF_START), text.index(PERF_END) + len(PERF_END)
    return text[a:b]


def main(argv):
    text = open(README, encoding="utf-8").read()
    if "--check" in argv:
        ok = readme_section(text) == render()
        print("README tables match the CSVs" if ok else "README tables differ from the CSVs")
        return 0 if ok else 1
    if "--write" in argv:
        with open(README, "w", encoding="utf-8") as f:
            f.write(text.replace(readme_section(text), render()))
        return 0
    print(render())
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
